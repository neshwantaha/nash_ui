/// Dimension tokens for common element sizes.
abstract final class AppDimensions {
  AppDimensions._();

  /// Standard button height.
  static const double button = 48;

  /// Small button height.
  static const double buttonSmall = 36;

  /// Standard input field height.
  static const double input = 52;

  /// AppBar / top bar height.
  static const double appBar = 56;

  /// Bottom navigation bar height.
  static const double bottomBar = 64;

  /// Navigation rail width.
  static const double navRail = 80;

  /// Sidebar width (desktop).
  static const double sidebar = 260;

  /// Maximum content width for desktop layouts.
  static const double contentMax = 1200;

  /// Standard icon size.
  static const double icon = 24;

  /// Small icon size.
  static const double iconSmall = 16;

  /// Large icon size.
  static const double iconLarge = 32;

  /// Standard avatar size.
  static const double avatar = 40;

  /// Default page horizontal padding.
  static const double pagePadding = 16;

  /// Dialog max width.
  static const double dialogWidth = 400;
}

/// Icon size tokens.
abstract final class AppIconsize {
  AppIconsize._();

  static const double xxs = 12;
  static const double xs = 16;
  static const double sm = 20;
  static const double md = 24;
  static const double lg = 28;
  static const double xl = 32;
  static const double xxl = 40;
  static const double xxxl = 48;
  static const double huge = 64;
  static const double massive = 96;
}
